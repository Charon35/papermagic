"""Чистий аркуш для процес-відео: прибирає з листа 3 друкований логотип, блок інструкції
(текст + ножиці/клей) і напис на стрічці — у кадрі не має бути жодного тексту чи лого.
python3 -I clean.py SHEET.jpg OUT.png"""
import sys, cv2
im = cv2.imread(sys.argv[1])
for x0, y0, x1, y1 in [(3, 3, 104, 92),        # логотип угорі ліворуч
                       (198, 6, 388, 148),     # «Інструкція…» + ножиці й клей
                       (238, 547, 335, 573)]:  # слово на середній панелі стрічки
    im[y0:y1, x0:x1] = 255
cv2.imwrite(sys.argv[2], im)
